    let toolCallCount = 0;

    const KNOWN_TOOLS = ['listAllFoodItems','searchFoodItems','getFoodItemDetails','getFoodPrice','getFoodOptions','webSearch','browseWebUrl','createReservation','checkReservationStatus','getCartItems','addCartItem','removeCartItem','showMenuSearch'];

    function tryParseToolJson(str) {
        try {
            const obj = JSON.parse(str);
            if (obj && obj.tool && typeof obj.tool === 'string') return obj;
        } catch (e) {}
        return null;
    }

    function findJsonObjects(text) {
        const results = [];
        for (let i = 0; i < text.length; i++) {
            if (text[i] === '{') {
                let depth = 0;
                let inString = false;
                let escape = false;
                for (let j = i; j < text.length; j++) {
                    const ch = text[j];
                    if (escape) { escape = false; continue; }
                    if (ch === '\\') { escape = true; continue; }
                    if (ch === '"') { inString = !inString; continue; }
                    if (inString) continue;
                    if (ch === '{') depth++;
                    if (ch === '}') {
                        depth--;
                        if (depth === 0) {
                            const candidate = text.substring(i, j + 1);
                            const parsed = tryParseToolJson(candidate);
                            if (parsed) results.push(parsed);
                            break;
                        }
                    }
                }
            }
        }
        return results;
    }

    function extractToolCalls(text) {
        const results = [];
        // Layer 1: Match <tool_call>...</tool_call> tags
        const tagRegex = /<tool_call>([\s\S]*?)<\/tool_call>/gi;
        let m;
        while ((m = tagRegex.exec(text)) !== null) {
            const inner = m[1].trim().replace(/```json\s*/g, '').replace(/```\s*/g, '');
            const parsed = tryParseToolJson(inner);
            if (parsed) results.push(parsed);
        }
        if (results.length > 0) return results;

        // Layer 2: AI wraps JSON in ```...``` code blocks
        const codeBlockRegex = /```(?:json)?\s*([\s\S]*?)\s*```/gi;
        while ((m = codeBlockRegex.exec(text)) !== null) {
            const parsed = tryParseToolJson(m[1].trim());
            if (parsed) results.push(parsed);
        }
        if (results.length > 0) return results;

        // Layer 3: Bare JSON with proper bracket matching (handles nested objects/arrays)
        const bareResults = findJsonObjects(text);
        for (const obj of bareResults) {
            if (KNOWN_TOOLS.includes(obj.tool)) results.push(obj);
        }
        if (results.length > 0) return results;

        // Layer 4: Last resort — any JSON with a "tool" key
        const allJson = findJsonObjects(text);
        for (const obj of allJson) {
            if (obj.tool) results.push(obj);
        }

        console.log('[extractToolCalls] input:', text.substring(0, 500), '| found:', results.length);
        return results;
    }

    async function handleAgentResponse(responseText) {
        const textClean = stripThinking(responseText);
        const toolCalls = extractToolCalls(textClean);

        if (toolCalls.length > 0) {
            toolCallCount++;
            if (toolCallCount > 4) {
                removeLoadingBubble();
                const limitMsgs = {
                    vi: "Hệ thống: AI đã dừng lại để tránh quá tải hạn ngạch API.",
                    en: "System: AI stopped to avoid API quota overload.",
                    fi: "Järjestelmä: AI pysäytettiin API-kvotaan liiallista välttämiseksi."
                };
                appendBubble(limitMsgs[getCurrentLang()] || limitMsgs.en, 'ai');
                return;
            }

            // Show any text before the first tool_call to the user
            const textBeforeTools = textClean.replace(/<tool_call>[\s\S]*?<\/tool_call>/gi, '').replace(/```json[\s\S]*?```/gi, '').trim();
            if (textBeforeTools.length > 0) {
                removeLoadingBubble();
                appendBubble(textBeforeTools, 'ai');
            }

            const results = [];
            for (const payload of toolCalls) {
                try {
                    const { tool, args } = payload;
                    let result;
                    if (tool === 'listAllFoodItems') {
                        result = await listAllFoodItems();
                    } else if (tool === 'searchFoodItems') {
                        result = await searchFoodItems(args?.query);
                    } else if (tool === 'getFoodItemDetails') {
                        result = await getFoodItemDetails(args?.nameOrId);
                    } else if (tool === 'getFoodPrice') {
                        result = await getFoodPrice(args?.nameOrId);
                    } else if (tool === 'getFoodOptions') {
                        result = await getFoodOptions(args?.nameOrId);
                    } else if (tool === 'webSearch') {
                        result = await webSearch(args?.query);
                    } else if (tool === 'browseWebUrl') {
                        result = await browseWebUrl(args?.url);
                    } else if (tool === 'createReservation') {
                        result = await createReservation(args?.name, args?.phone, args?.email, args?.date, args?.time, args?.guests, args?.location, args?.notes);
                    } else if (tool === 'checkReservationStatus') {
                        result = await checkReservationStatus(args?.phone);
                    } else if (tool === 'getCartItems') {
                        result = await getCartItems();
                    } else if (tool === 'addCartItem') {
                        result = await addCartItem(args?.name, args?.qty, args?.options);
                    } else if (tool === 'removeCartItem') {
                        result = await removeCartItem(args?.name);
                    } else if (tool === 'showMenuSearch') {
                        result = await showMenuSearch(args?.query);
                    } else {
                        const notSupportedMsgs = {
                            vi: `Tool ${tool} không được hỗ trợ.`,
                            en: `Tool ${tool} is not supported.`,
                            fi: `Työkalua ${tool} ei tueta.`
                        };
                        result = { error: notSupportedMsgs[getCurrentLang()] || notSupportedMsgs.en };
                    }
                    if (result && typeof result === 'object' && result.hasOwnProperty('error')) {
                        results.push({ tool, success: false, error: result.error });
                    } else {
                        results.push({ tool, success: true, result });
                    }
                } catch (e) {
                    results.push({ tool: payload?.tool || 'unknown', success: false, error: e.message });
                }
            }

            const feedbackContent = results.map((r, idx) => `[Tool Result ${idx + 1} - ${r.tool}]: ${JSON.stringify(r.result || { error: r.error })}`).join('\n\n');
            const feedbackPrompts = {
                vi: `Dưới đây là kết quả của các công cụ tra cứu bạn đã gọi:\n\n${feedbackContent}\n\nHãy tổng hợp kết quả này và trả lời khách hàng.`,
                en: `Here are the results from the tools you called:\n\n${feedbackContent}\n\nPlease summarize these results and respond to the customer.`,
                fi: `Tässä on työkalujen tulokset:\n\n${feedbackContent}\n\nOle hyvä ja tiivistä nämä tulokset ja vastaa asiakkaalle.`
            };
            chatMessages.push({
                role: 'user',
                content: feedbackPrompts[getCurrentLang()] || feedbackPrompts.en
            });
            saveChatHistory();

            appendLoadingBubble();
            await fetchAiResponse();
        } else {
            removeLoadingBubble();
            appendBubble(textClean, 'ai');
        }
    }

    async function fetchAiResponse() {
        try {
            let data;
            try {
                data = await callCerebras({ messages: chatMessages }, 'gpt-oss-120b');
            } catch (primaryErr) {
                try {
                    data = await callCerebras({ messages: chatMessages }, 'zai-glm-4.7');
                } catch (backupErr) {
                    data = await callOpenRouterWithFallback({ messages: chatMessages });
                }
            }

            const responseText = data.choices[0].message.content || '';
            
            // Also check for OpenAI-style tool_calls in response object
            const nativeToolCalls = data.choices[0].message.tool_calls;
            if (nativeToolCalls && nativeToolCalls.length > 0 && (!responseText || responseText.trim() === '')) {
                const synthesized = nativeToolCalls.map(tc => {
                    const fn = tc.function || {};
                    let args = {};
                    try { args = typeof fn.arguments === 'string' ? JSON.parse(fn.arguments) : fn.arguments; } catch(e) {}
                    return `<tool_call>${JSON.stringify({ tool: fn.name, args })}</tool_call>`;
                }).join('\n');
                data.choices[0].message.content = synthesized;
            }
            
            const finalText = data.choices[0].message.content;
            chatMessages.push({ role: 'assistant', content: finalText });
            saveChatHistory();
            await handleAgentResponse(finalText);
        } catch (err) {
            const errMessages = {
                vi: 'Lỗi kết nối AI: ',
                en: 'AI connection error: ',
                fi: 'AI yhteysvirhe: '
            };
            const errMsg = errMessages[getCurrentLang()] || errMessages.en;
            removeLoadingBubble();
            appendBubble(`${errMsg}${err.message}`, 'ai');
        }
    }

